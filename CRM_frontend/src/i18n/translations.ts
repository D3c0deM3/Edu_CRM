export const languageOptions: Array<{ code: LanguageCode; label: string }> = [
  { code: 'en', label: 'EN' },
  { code: 'ru', label: 'RU' },
  { code: 'uz', label: 'UZ' },
];

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const buildReplacementEntries = (language: Exclude<LanguageCode, 'en'>) =>
  Object.entries(translations[language]).sort((left, right) => right[0].length - left[0].length);

const replacementEntries = {
  ru: buildReplacementEntries('ru'),
  uz: buildReplacementEntries('uz'),
};

const regexTransforms: Record<Exclude<LanguageCode, 'en'>, Array<(value: string) => string>> = {
  ru: [
    (value) => value.replace(/^(\d+)\s+of\s+(\d+)\s+completed$/i, '$1 из $2 завершено'),
    (value) => value.replace(/^Pending Tests \((\d+)\)$/i, 'Ожидающие тесты ($1)'),
    (value) => value.replace(/^Students with Payment Issues \((\d+)\)$/i, 'Студенты с проблемами оплаты ($1)'),
  ],
  uz: [
    (value) => value.replace(/^(\d+)\s+of\s+(\d+)\s+completed$/i, '$1 / $2 yakunlangan'),
    (value) => value.replace(/^Pending Tests \((\d+)\)$/i, 'Kutilayotgan testlar ($1)'),
    (value) => value.replace(/^Students with Payment Issues \((\d+)\)$/i, 'To‘lov muammosi bor talabalar ($1)'),
  ],
};

export const translateText = (value: string, language: LanguageCode): string => {
  if (language === 'en' || !value) {
    return value;
  }

  let translatedValue = value;

  replacementEntries[language].forEach(([source, target]) => {
    translatedValue = translatedValue.replace(new RegExp(escapeRegExp(source), 'g'), target);
  });

  regexTransforms[language].forEach((transform) => {
    translatedValue = transform(translatedValue);
  });

  return translatedValue;
};
